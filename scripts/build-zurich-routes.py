"""Bundle simplified official Zurich transit alignments. Requires shapely and pyproj.

Raw CCZero canton data are cached under build/, not fetched by the game.
One documented direction per route is used as a bidirectional game shuttle.
"""
from pathlib import Path
import json
import math
import urllib.parse
import urllib.request
from pyproj import Transformer
from shapely.geometry import shape, LineString, box
from shapely.ops import transform, linemerge

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / "build/city-source"
CACHE.mkdir(parents=True, exist_ok=True)
SOURCE = "https://maps.zh.ch/wfs/OGDZHWFS"
to_lv95 = Transformer.from_crs(4326, 2056, always_xy=True)
CENTER_E, CENTER_N = to_lv95.transform(8.5417, 47.3769)


def project(lon, lat):
    return local(*to_lv95.transform(lon, lat))


def local(east, north):
    return ((east - CENTER_E) / 100, (CENTER_N - north) / 100)


def load(name, layer):
    path = CACHE / (name + ".json")
    if not path.exists():
        query = urllib.parse.urlencode(dict(SERVICE="WFS", VERSION="1.0.0", REQUEST="GetFeature",
                                             TYPENAME=layer, OUTPUTFORMAT="application/json", SRSNAME="EPSG:2056"))
        path.write_bytes(urllib.request.urlopen(SOURCE + "?" + query, timeout=90).read())
    data = json.loads(path.read_bytes())
    assert "2056" in data["crs"]["properties"]["name"], "Unexpected source coordinate system"
    return data["features"]


features = load("lines", "ogd-0108_giszhpub_zvv_linien_gen_l")
rail = load("rail", "ogd-0108_giszhpub_zvv_s_bahn_linien_l")
west, north = project(8.44, 47.44)
east, south = project(8.63, 47.31)
extent = box(west, north, east, south)
paths, stop_names, provenance = {}, {}, {}
for ident, number, operator in [("b31", "31", "02"), ("b33", "33", "02"), ("t4", "4", "01"), ("t8", "8", "01"), ("s12", "S12", None)]:
    candidates = rail if operator is None else features
    feature = next(f for f in candidates if
                   (f["properties"].get("liniesbahn") == number if operator is None else
                    f["properties"].get("liniennummer") == number and
                    f["properties"].get("betriebszweig") == operator and f["properties"].get("richtung") == 0))
    geom = transform(local, shape(feature["geometry"]))
    geom = geom.intersection(extent)
    if geom.geom_type == "MultiLineString":
        geom = linemerge(geom)
    if geom.geom_type != "LineString":
        geom = max((g for g in geom.geoms if g.geom_type == "LineString"), key=lambda g: g.length)
    # 1.5m tolerance preserves road bends without making every frame process surveying vertices.
    geom = geom.simplify(0.015, preserve_topology=True)
    paths[ident] = list(geom.coords)
    props = feature["properties"]
    if operator:
        stop_names[ident] = [props["anfangshaltestelle"].removeprefix("Zürich, "), props["endhaltestelle"].removeprefix("Zürich, ")]
    else:
        stop_names[ident] = ["Altstetten", "Hauptbahnhof", "Stadelhofen", "Stettbach"]
    provenance[ident] = dict(source=SOURCE, feature=feature.get("id"), properties=props,
                             vertices=len(paths[ident]), lengthMeters=round(geom.length * 100),
                             note="Simplified one-direction geometry, clipped to map; S12 retains longest connected component.")

# Deliberately fictional expansions remain clearly labelled in the UI.
fiction = {
    "m1": [(8.544, 47.399), (8.543, 47.390), (8.541, 47.378), (8.539, 47.369), (8.532, 47.360)],
    "l1": [(8.5429, 47.3658), (8.5449, 47.3641), (8.5480, 47.3606), (8.5521, 47.3568), (8.5565, 47.3533)],
    "c1": [(8.5086, 47.3596), (8.5033, 47.3550), (8.4916, 47.3494)],
    "a1": [(8.490, 47.392), (8.512, 47.408), (8.545, 47.426), (8.585, 47.434)],
}
for ident, coords in fiction.items():
    paths[ident] = [project(*point) for point in coords]
stop_names.update(m1=["Milchbuck", "Hauptbahnhof", "Paradeplatz", "Enge"],
                  l1=["Bürkliplatz", "Zürichhorn"], c1=["Friesenberg", "Uetliberg"],
                  a1=["Stadtflugplatz (Spiel)", "Weltverbindung (Spiel)"])

out = ["// Generated by scripts/build-zurich-routes.py. Source: Canton Zurich CCZero.",
       "// Real alignments: b31, b33, t4, t8, s12. Others: explicitly fictional game routes.",
       "import Foundation", "", "public enum ZurichRouteGeometry {", "    public static let paths: [String: [MapPoint]] = ["]
for ident, points in paths.items():
    values = ",".join(f".init({x:.4f},{z:.4f})" for x, z in points)
    out.append(f'        "{ident}": [{values}],')
out += ["    ]", "    public static let stops: [String: [String]] = ["]
for ident, names in stop_names.items():
    out.append(f'        "{ident}": {json.dumps(names, ensure_ascii=False)},')
out += ["    ]", "}", ""]
(ROOT / "native/Sources/TaktCore/ZurichRouteGeometry.swift").write_text("\n".join(out), encoding="utf-8")
(CACHE / "route-provenance.json").write_text(json.dumps(provenance, ensure_ascii=False, indent=2), encoding="utf-8")
for ident, points in paths.items():
    print(ident, len(points), "vertices", round(LineString(points).length * 100), "meters")
